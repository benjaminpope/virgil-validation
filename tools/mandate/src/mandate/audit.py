"""Reading the campaign back: the status page and the audit.

Both are generated from the plan, the registry, the docket and the ledger. Nobody writes them.
"""

from __future__ import annotations

import json
import pathlib

from .model import DOCKET, Campaign, git, matches
from .orders import Order, expand, superseded, unassigned
from .work import digest, out_dir

STATES = ("pass", "warn", "fail", "error", "ready", "waiting", "blocked", "parked")


def describe(e: dict) -> str:
    kind = e["kind"]
    if kind == "decide":
        what = f"{e['stage']}/{e['key']}: " + ", ".join(f"{k}={v}" for k, v in e["set"].items())
    elif kind == "exclude":
        what = ", ".join(f"{k}={v}" for k, v in e["where"].items())
        what += f" from {', '.join(e['stages'])}" if e.get("stages") else " from every stage"
    elif kind == "annotate":
        what = ", ".join(f"{k}={v}" for k, v in e["where"].items()) + ": "
        what += ", ".join(f"{k}={v}" for k, v in e["set"].items())
    else:
        what = f"{e.get('stage')}" + (f"/{e['key']}" if e.get("key") else "")
    return f"`{e['id']}` {kind} {what}. {e['why']} ({e['by']}, {e['at'][:10]})"


def status_page(c: Campaign, orders: dict[str, list[Order]] | None = None) -> str:
    orders = orders or expand(c)
    lines = [f"# {c.plan.get('campaign', c.root.name)}: status", "",
             "Generated by `mandate status` from the plan, the registry, the docket and the ledger. Do not edit.", ""]
    commit = git(c.root, "log", "-1", "--format=%h %cs", "--", "mandate.yaml", "registry")
    lines += [f"Plan and registry last changed at commit {commit or '(uncommitted)'}; {len(c.units)} units.", ""]
    pending = c.pending()
    lines += [f"## Waiting for a person ({len(pending)})", ""]
    lines += [f"- {describe(e)}" for e in pending] or ["Nothing."]
    lines += ["", "## Stages", "", "| stage | worker | orders | " + " | ".join(STATES) + " |",
              "|---|---|---|" + "---|" * len(STATES)]
    for stage, os_ in orders.items():
        counts = [str(sum(o.state == s for o in os_) or "") for s in STATES]
        worker = c.stages[stage].get("worker", "code") + ("" if c.level(stage) == "open" else ", " + c.level(stage))
        lines.append(f"| {stage} | {worker} | {len(os_)} | " + " | ".join(counts) + " |")
    trouble = [o for os_ in orders.values() for o in os_ if o.state in ("fail", "error", "blocked", "parked")]
    lines += ["", f"## Needs attention ({len(trouble)})", ""]
    for o in trouble:
        why = o.reason or (o.attempts[-1].get("problem") if o.attempts else "") or ""
        bad = [k for k, v in (o.attempts[-1].get("checks") or {}).items() if v == "fail"] if o.attempts else []
        lines.append(f"- `{o.ref}` {o.state}" + (f": {why}" if why else "") + (f" (failing: {', '.join(bad)})" if bad else ""))
    if not trouble:
        lines.append("Nothing.")
    force = [e for e in c.docket if e["kind"] in ("decide", "exclude") and c.state(e) == "active"]
    notes = [e for e in c.docket if e["kind"] == "annotate" and c.state(e) == "active"]
    lines += ["", f"## Departures from the plan's defaults ({len(force)})", ""]
    lines += [f"- {describe(e)}" for e in force] or ["None: every order ran on defaults and rules."]
    closed = sum(c.state(e) in ("denied", "closed") for e in c.docket if e["kind"] != "resolve")
    lines += ["", f"Registry annotations in force: {len(notes)}. Denied or closed entries: {closed}.", ""]
    dropped = [(o, up, d) for os_ in orders.values() for o in os_ for up, ds in o.dropped.items() for d in ds
               if d["why"] != "not nearest"]
    lines += [f"## Dropped from ensembles ({len(dropped)})", ""]
    lines += [f"- `{o.ref}` dropped {d.get('stage', up)}/{d['key']}: {d['why']}" for o, up, d in dropped] or ["None."]
    retried = [o for os_ in orders.values() for o in os_ if len(o.attempts) > 1]
    lines += ["", f"## Orders attempted more than once ({len(retried)})", ""]
    for o in retried:
        rep = [a["reproduced"] for a in o.attempts if "reproduced" in a]
        note = "" if not rep else (" reproduced bit for bit" if all(rep) else " NOT reproduced bit for bit")
        lines.append(f"- `{o.ref}`: {len(o.attempts)} attempts ({', '.join(a['status'] for a in o.attempts)});{note}")
    if not retried:
        lines.append("None.")
    provisional = [o for os_ in orders.values() for o in os_ if o.attempts and _provisional(o.attempts[-1])]
    stale, loose = superseded(c, orders), unassigned(c)
    lines += ["", "## Housekeeping", "",
              f"- Results from an uncommitted campaign or an uncommitted pinned checkout (provisional): {len(provisional)}",
              f"- Superseded orders kept in the ledger: {len(stale)}",
              f"- Units no stage selects: {len(loose)}"
              + (" (" + ", ".join(u.get(c.unit_id, '?') for u in loose[:8]) + (" ..." if len(loose) > 8 else "") + ")"
                 if loose else ""), ""]
    return "\n".join(lines)


def _provisional(attempt: dict) -> bool:
    versions = attempt.get("versions") or {}
    return bool((attempt.get("campaign") or {}).get("dirty")) or any(v.get("dirty") for v in versions.values())


def verify(c: Campaign, base: str | None = None) -> dict[str, list[str]]:
    """Audit the campaign. ``violations`` are broken rules; ``review`` is for the person who merges.

    With ``base`` (a git ref, usually the main branch) it also classifies what changed since:
    workers add ledger records and docket lines; anything else is a change of mandate.
    """
    out: dict[str, list[str]] = {"violations": [], "review": [], "info": []}
    out["violations"] += c.problems()
    orders = expand(c)
    current = {(s, o.id): o for s, os_ in orders.items() for o in os_ if o.id}
    ids = {e["id"] for e in c.docket}
    checked = absent = 0
    ledger = c.root / "ledger"
    for folder in sorted(ledger.glob("*/*")) if ledger.exists() else []:
        if not folder.is_dir():
            continue
        ref = f"{folder.parent.name}/{folder.name}"
        if not (folder / "order.json").exists():
            out["violations"].append(f"{ref}: attempts without an order")
            continue
        order = json.loads((folder / "order.json").read_text())
        if git(c.root, "cat-file", "-e", f"{order.get('plan_commit')}^{{commit}}") is None:
            out["violations"].append(f"{ref}: plan commit {order.get('plan_commit')} is not in this repository")
        for d in (order.get("decisions") or {}).values():
            src = d.get("source", "")
            if src.startswith("docket:") and src[7:] not in ids:
                out["violations"].append(f"{ref}: decision cites {src}, which is not in the docket")
        attempts = [json.loads(p.read_text()) for p in sorted(folder.glob("attempt-*.json"))]
        if [a.get("n") for a in attempts] != list(range(1, len(attempts) + 1)):
            out["violations"].append(f"{ref}: attempts are not numbered 1..{len(attempts)} (one is missing or renamed)")
        if any(a.get("order") != folder.name for a in attempts):
            out["violations"].append(f"{ref}: an attempt belongs to another order")
        o = current.get((folder.parent.name, folder.name))
        if o and attempts:
            run_folder = out_dir(c, o)
            if run_folder.exists():
                checked += 1
                if digest(run_folder, c.stages[o.stage].get("digest")) != attempts[-1].get("digest"):
                    out["violations"].append(f"{ref}: the run folder no longer matches the recorded attempt")
            else:
                absent += 1
            if _provisional(attempts[-1]):
                out["review"].append(f"{ref}: provisional (run from uncommitted code)")
    out["info"].append(f"run folders checked against their records: {checked}; not on this machine: {absent}")
    worded = [e for e in c.docket
              if e["kind"] != "resolve" and e.get("by") in c.humans and c.needs_human({**e, "by": None})]
    out["info"] += [f"in force on a person's word: {describe(e)}" for e in worded if e["kind"] != "annotate"]
    if any(e["kind"] == "annotate" for e in worded):
        n = sum(e["kind"] == "annotate" for e in worded)
        out["info"].append(f"registry annotations made directly by a person: {n}")
    if base:
        _since(c, base, out)
    return out


def _since(c: Campaign, base: str, out: dict[str, list[str]]) -> None:
    top = git(c.root, "rev-parse", "--show-toplevel")
    diff = git(c.root, "diff", "--name-status", "--no-renames", f"{base}...HEAD", "--", ".")
    if top is None or diff is None:
        out["violations"].append(f"cannot compare with {base!r}")
        return
    here = c.root.relative_to(pathlib.Path(top).resolve()).as_posix()
    prefix = "" if here == "." else here + "/"
    for line in diff.splitlines():
        status, path = line.split("\t", 1)
        rel = path.removeprefix(prefix)
        if rel.startswith("ledger/"):
            if status != "A":
                out["violations"].append(f"ledger record changed or removed since {base}: {rel}")
        elif rel == DOCKET:
            old = (git(c.root, "show", f"{base}:{path}") or "").splitlines()
            new = (c.root / DOCKET).read_text().splitlines() if (c.root / DOCKET).exists() else []
            if [x for x in old if x.strip()] != [x for x in new if x.strip()][: len([x for x in old if x.strip()])]:
                out["violations"].append(f"docket lines changed or removed since {base}: the docket is append-only")
            fresh = [json.loads(x) for x in new if x.strip() and x not in old]
            for e in fresh:
                if e["kind"] == "resolve":
                    out["review"].append(f"resolved since {base}: {e['of']} {e['verdict']} by {e['by']}: {e['why']}")
                elif c.state(e) == "active":
                    out["review"].append(f"in force since {base}: {describe(e)}")
        elif rel == "STATUS.md":
            continue
        elif rel == "mandate.yaml" or rel.split("/")[0] in ("registry", "notes", "prompts", "playbooks"):
            out["review"].append(f"MANDATE CHANGED since {base} ({status}): {rel}")
        else:
            out["review"].append(f"changed since {base} ({status}): {rel}")


def touched(c: Campaign, where: dict) -> int:
    return sum(matches(u, where) for u in c.units)
